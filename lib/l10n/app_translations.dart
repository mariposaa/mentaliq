  }

  /// Parameterized translation: replaces {0}, {1}, … with args.
  static String format(String key, List<String> args) {
    var text = get(key);
    for (var i = 0; i < args.length; i++) {
      text = text.replaceAll('{$i}', args[i]);
    }
    return text;
  }

